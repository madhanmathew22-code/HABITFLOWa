package com.habitflow.app.data.repository

import com.habitflow.app.data.local.entity.HabitEntity
import com.habitflow.app.domain.model.Habit

fun HabitEntity.toDomain(): Habit = Habit(
    id = id,
    name = name,
    description = description,
    iconKey = iconKey,
    colorArgb = colorArgb,
    categoryId = categoryId,
    frequencyType = frequencyType,
    weekdaysMask = weekdaysMask,
    timesPerWeek = timesPerWeek,
    timesPerMonth = timesPerMonth,
    everyNDays = everyNDays,
    flexibleWindowDays = flexibleWindowDays,
    valueType = valueType,
    targetQuantity = targetQuantity,
    unit = unit,
    difficulty = difficulty,
    startDate = startDate,
    endDate = endDate,
    notes = notes,
    isArchived = isArchived,
    isPinned = isPinned,
    isFavorite = isFavorite,
    sortOrder = sortOrder,
    stackAfterHabitId = stackAfterHabitId,
    dependsOnHabitId = dependsOnHabitId,
)

